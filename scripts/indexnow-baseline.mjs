// Runs before `next build`. On a PRODUCTION Vercel build only, it snapshots the
// sitemap that is still live (the previous deploy's) into
// lib/indexNowBaseline.generated.ts, so that after this deploy goes live
// /api/indexnow can submit exactly the pages that are new or whose <lastmod>
// moved. Everywhere else it does nothing, and it never fails the build: if the
// fetch goes wrong the baseline stays null and nothing is submitted.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

if (process.env.VERCEL_ENV !== "production") process.exit(0);

const site = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://www.recipeprinter.com").replace(/\/$/, "");
const target = fileURLToPath(new URL("../lib/indexNowBaseline.generated.ts", import.meta.url));

try {
  const response = await fetch(`${site}/sitemap.xml`, { signal: AbortSignal.timeout(10_000) });
  if (!response.ok) throw new Error(`HTTP ${response.status}`);
  const xml = await response.text();

  const previous = {};
  for (const [, block] of xml.matchAll(/<url>([\s\S]*?)<\/url>/g)) {
    const loc = block.match(/<loc>\s*([^<]+?)\s*<\/loc>/)?.[1];
    const lastmod = block.match(/<lastmod>\s*([^<]+?)\s*<\/lastmod>/)?.[1] ?? "";
    if (loc) previous[loc] = lastmod;
  }
  if (Object.keys(previous).length === 0) throw new Error("no <url> entries");

  writeFileSync(
    target,
    "// Generated by scripts/indexnow-baseline.mjs during the production build.\n" +
      `export const PREVIOUS_SITEMAP: Record<string, string> | null = ${JSON.stringify(previous, null, 2)};\n`,
  );
  console.log(`[indexnow] baseline: ${Object.keys(previous).length} URLs from ${site}/sitemap.xml`);
} catch (error) {
  console.warn(`[indexnow] no baseline (${error.message}); this deploy will submit nothing`);
}
